from itertools import combinations, permutations
import pandas as pd

# 投票クラス
class Bet:
  # コンストラクタ
  def __init__(self, bet_type: str, wheel: bool, list_1: list[int], list_2: list[int] = [], list_3: list[int] = [], memo: str = ''):
    self.__bet_type = bet_type
    self.__bet_list = make_three_horse_bets(bet_type, list_1, list_2, list_3, wheel, len(list_3) == 0, len(list_2) == 0)
    self.__origin_list = [list_1, list_2, list_3]
    self.__memo = memo

  @property
  def bet_type(self): return self.__bet_type
  @property
  def bet_list(self): return self.__bet_list.copy()
  @property
  def origin_list(self): return self.__origin_list.copy()
  @property
  def memo(self): return self.__memo

  # DataFrame作成
  def make_dataframe(self, id: str) -> pd.DataFrame:
    def conv(x: str) -> str:
        if x == 'Win': return '単勝'
        if x == 'Place': return '複勝'
        if x == 'Bracket': return '枠連'
        if x == 'Quinella': return '馬連'
        if x == 'QuinellaPlace': return 'ワイド'
        if x == 'Exacta': return '馬単'
        if x == 'Trio': return '三連複'
        if x == 'Trifecta': return '三連単'
        
        return '無し'
    data = {}
    data['Id'] = [id]
    data['BetType'] = [conv(self.__bet_type)]
    data['List1'] = ', '.join([str(self.origin_list[0]).replace('np.int64(', '').replace(')', '')])
    data['List2'] = ', '.join([str(self.origin_list[1]).replace('np.int64(', '').replace(')', '')])
    data['List3'] = ', '.join([str(self.origin_list[2]).replace('np.int64(', '').replace(')', '')])
    data['Memo'] = self.__memo
    data['BetCount'] = len(self.__bet_list) * 100
    return pd.DataFrame(data)


# 買い目の生成
# Generated by ChatGPT
def make_three_horse_bets(bet_type: str, list_1: list[int], list_2: list[int], list_3: list[int], wheel: bool = False, one_head_axis: bool = False, box: bool = False) -> list[int]:
  if bet_type == 'None': return []

  bet_list = []
  if bet_type in ['Win', 'Place']:
      # ■ 単勝・複勝（１頭軸のみ）
      # list_1 に含まれる馬番をすべて列挙
      for h1 in list_1:
          bet_list.append([h1])
      return bet_list

  num = 3 if bet_type in ['Trio', 'Trifecta'] else 2

  #-------------------------------
  # 1. ボックス（box = True）
  #-------------------------------
  #   - list_1, list_2, list_3 の全馬番のユニオンをとって
  #     三連複は combination、三連単は permutation で全列挙
  #-------------------------------
  if box:
      union_123 = list(set(list_1 + list_2 + list_3))
      union_123.sort()

      if bet_type in ['Trio', 'Quinella', 'QuinellaPlace']:
          # 三連複 → 組み合わせ
          for combi in combinations(union_123, num):
              bet_list.append(sorted(combi))
      else:
          # 三連単 → 順列
          for perm in permutations(union_123, num):
              bet_list.append(list(perm))
      return bet_list

  #-------------------------------
  # 2. 1頭軸流し（one_head_axis = True）
  #-------------------------------
  #   - 例として、list_1 が「軸候補」の馬番を持っている想定
  #   - 残りの馬番（list_2 + list_3）から2頭を選んで三連複 or 三連単を作る
  #-------------------------------
  if one_head_axis:
      anchor_list = list_1  # 軸にする馬のリスト
      others = list(set(list_2 + list_3))
      
      if bet_type in ['Trio', 'Quinella', 'QuinellaPlace']:
          # 【三連複】軸1頭 + 相手2頭（組み合わせ）
          for anchor in anchor_list:
              for combi in combinations(others, num - 1):
                  if anchor not in combi:
                      # 軸とかぶらないようにチェック(不要なら省略可)
                      trio_combo = [anchor] + list(combi)
                      bet_list.append(sorted(trio_combo))
      else:
          # 【三連単】軸1頭(1着想定) + 相手2頭(2着3着)の順列
          for anchor in anchor_list:
              # 2着3着で順番がある
              for perm in permutations(others, num - 1):
                  if anchor not in perm:
                      trifecta_perm = [anchor, perm[0], perm[1]] if num == 3 else [anchor, perm[0]]
                      bet_list.append(trifecta_perm)
      return bet_list

  #-------------------------------
  # 3. wheel = True（フォーメーション・流し）
  #-------------------------------
  #   - ここではあくまで例として、
  #     list_1 = 1頭目候補, list_2 = 2頭目候補, list_3 = 3頭目候補
  #-------------------------------
  if wheel:
    if num == 3:
        if bet_type == 'Trio':
            # 三連複 → 順番不問
            #   1頭目候補(list_1), 2頭目候補(list_2), 3頭目候補(list_3)から
            #   同じ馬番にならないように組み合わせ
            for h1 in list_1:
                for h2 in list_2:
                    for h3 in list_3:
                        if h1 != h2 and h2 != h3 and h1 != h3:
                            bet_list.append(sorted([h1, h2, h3]))
        else:
            # 三連単 → 順番あり
            for h1 in list_1:
                for h2 in list_2:
                    for h3 in list_3:
                        # 同じ馬番を重複で使わない
                        if h1 != h2 and h2 != h3 and h1 != h3:
                            bet_list.append([h1, h2, h3])
        return bet_list
    else:
        if bet_type != 'Exacta':
            # 馬単以外 → 順番不問
            #   1頭目候補(list_1), 2頭目候補(list_2), 3頭目候補(list_3)から
            #   同じ馬番にならないように組み合わせ
            for h1 in list_1:
                for h2 in list_2:
                    if h1 != h2:
                        bet_list.append(sorted([h1, h2]))
            else:
                # 馬単 → 順番あり
                for h1 in list_1:
                    for h2 in list_2:
                        # 同じ馬番を重複で使わない
                        if h1 != h2:
                            bet_list.append([h1, h2])
            return bet_list

  #-------------------------------
  # 4. 上記以外 (wheel=False, one_head_axis=False, box=False) → 
  #    すべての馬番をまとめて全パターン列挙
  #-------------------------------
  union_123 = list(set(list_1 + list_2 + list_3))
  union_123.sort()

  if bet_type in ['Trio', 'Quinella', 'QuinellaPlace']:
      # 組み合わせ
      for combi in combinations(union_123, num):
          bet_list.append(list(combi))
  else:
      # 順列
      for perm in permutations(union_123, num):
          bet_list.append(list(perm))

  return bet_list
